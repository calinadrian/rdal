const { app, BrowserWindow, ipcMain } = require('electron');
const fs = require('fs');
const path = require('path');
const workspace = path.resolve(__dirname, '..');
const args = process.argv.filter(arg => !arg.startsWith('--'));
const root = args[2] ? path.resolve(args[2]) : workspace;
app.setPath('userData', require('./test-profile.cjs').testProfile('quest-filter')); // removed after the test ends
const db = JSON.parse(fs.readFileSync(path.join(root, 'data/db.json')));
let preferences = {};
ipcMain.handle('db:get', () => db);
ipcMain.handle('settings:get', () => ({ hotkey: 'Control+Shift+L', mode: 'window' }));
ipcMain.handle('preferences:get', () => preferences);
ipcMain.on('preferences:commit', (event, patch) => { preferences = { ...preferences, ...patch }; event.returnValue = { ok: true }; });
app.whenReady().then(async () => {
  const win = new BrowserWindow({ width: 1280, height: 850, show: false,
    webPreferences: { preload: path.join(root, 'app/preload.js'), sandbox: false, backgroundThrottling: false } });
  const timeout = setTimeout(() => { console.error('Quest filter test timed out'); app.exit(1); }, 20000);
  try {
    await win.loadFile(path.join(root, 'app/ui/index.html'));
    win.showInactive(); await new Promise(r => setTimeout(r, 800));
    console.log(await win.webContents.executeJavaScript(`(async () => {
      const assert = (ok, message) => { if (!ok) throw Error(message); };
      const wait = ms => new Promise(r => setTimeout(r, ms));
      state.module = 'map'; setMapMode(true); renderModules();
      const select = document.querySelector('#quest-map-filter select');
      const choose = mode => { select.value = mode; select.dispatchEvent(new Event('change', { bubbles: true })); };
      const chooseSteps = mode => { const s = document.querySelector('#quest-map-steps'); s.value = mode; s.dispatchEvent(new Event('change', { bubbles: true })); };
      const quest = name => db.map.markers.find(m => m.c === 'quest' && m.ref === name);
      const rat = quest('Ratcatcher'), cook = quest("Cook's Assistant"), melody = quest('A Melody Remembered');
      choose('active'); questLog = null; renderQuestMapFilter();
      assert(!questMapMarkerVisible(rat) && !questMapMarkerVisible(cook), 'No snapshot must not invent active quests');
      onQuestLog([{ id: 'Quest_FTUE_RC', s: 1, o: 'Objective1' }, { id: E["Cook's Assistant"].id, s: 1, o: 'Objective1' }]);
      assert(questMapMarkerVisible(rat) && questMapMarkerVisible(cook) && !questMapMarkerVisible(melody), 'Active mode must show all and only active quests');
      const ratReturn = db.map.markers.find(m => m.ref === 'Ratcatcher' && m.qnpc);
      const windmill = db.map.markers.find(m => m.ref === 'Ratcatcher' && m.qlocation === 'Windmill_Area_FTUE_RC');
      chooseSteps('current');
      assert(questMapMarkerVisible(rat) && !questMapMarkerVisible(ratReturn), 'Current-only must hide future steps');
      onQuestLog([{ id: 'Quest_FTUE_RC', s: 1, o: 'Objective2' }]);
      assert(!questMapMarkerVisible(rat) && questMapMarkerVisible(ratReturn) && questMapMarkerVisible(windmill), 'Progress must replace the previous step and retain every current objective location');
      assert(!questMapMarkerVisible({ ...windmill, qsteps: [] }), 'Current-only must hide unlinked steps');
      choose('all');
      assert(questMapMarkerVisible(melody), 'Unstarted quest pickups must remain available');
      choose('active'); chooseSteps('all');
      assert(questMapMarkerVisible(rat), 'All steps must restore earlier objectives');
      onQuestLog([{ id: 'Quest_FTUE_RC', s: 2 }, { id: E["Cook's Assistant"].id, s: 1, o: 'Objective1' }]);
      assert(!questMapMarkerVisible(rat) && questMapMarkerVisible(cook), 'Completed quest must disappear immediately in active mode');
      choose('selected');
      assert(!questMapMarkerVisible(cook), 'Empty selected list must hide every quest');
      const toggle = name => [...document.querySelectorAll('#quest-map-picker [data-quest]')].find(r => r.dataset.quest === name).querySelector('input').click();
      toggle('Ratcatcher'); toggle("Cook's Assistant");
      assert(questMapMarkerVisible(rat) && questMapMarkerVisible(cook) && !questMapMarkerVisible(melody), 'Selected mode must support multiple quests, including explicit completed selections');
      const search = document.querySelector('#quest-map-picker input[type=search]');
      search.value = 'rat'; search.dispatchEvent(new Event('input', { bubbles: true }));
      assert([...document.querySelectorAll('#quest-map-picker [data-quest]')].filter(r => !r.hidden).every(r => /rat/i.test(r.dataset.quest)), 'Search must filter quest choices');
      toggle('Ratcatcher');
      assert(document.querySelector('#quest-map-picker input[type=search]') === search && search.value === 'rat', 'Updating selection must preserve the search input');
      await wait(1300);
      MapView.setHighlight('Hidden quest test', [rat]); MapView.focusMarker(rat); await wait(100);
      const canvas = document.querySelector('#map'), r = canvas.getBoundingClientRect();
      canvas.dispatchEvent(new MouseEvent('mousemove', { bubbles: true, clientX: r.x + r.width / 2, clientY: r.y + r.height / 2 }));
      assert(document.querySelector('#map-tip').hidden, 'Filtered quest must not remain hoverable even in a highlighted result');
      const buttons = document.querySelectorAll('#quest-map-picker .creature-pool-actions button');
      buttons[0].click(); assert(questMapMarkerVisible(melody), 'Select all must select the catalogue');
      buttons[1].click(); assert(selectedMapQuests.size === 0 && !questMapMarkerVisible(melody), 'Clear must preserve an intentionally empty selection');
      choose('active'); showOnMap('Ratcatcher');
      assert(questMapMode === 'selected' && selectedMapQuests.has('Ratcatcher'), 'Explicit Show on map must include a quest excluded by active mode');
      choose('all');
      assert(!questMapMarkerVisible(rat) && questMapMarkerVisible(melody), 'All mode must preserve the usual completed-quest hiding');
      choose('selected'); buttons[1].click(); toggle('Ratcatcher'); toggle("Cook's Assistant");
      search.value = ''; search.dispatchEvent(new Event('input', { bubbles: true }));
      MapView.setHighlight(null); document.querySelector('#map-highlight').hidden = true;
      document.querySelector('#quest-map-picker').open = true;
      onQuestLog([{ id: 'Quest_FTUE_RC', s: 1, o: 'Objective2' }, { id: E["Cook's Assistant"].id, s: 1, o: 'Objective1' }]);
      chooseSteps('current');
      showOnMap('Ratcatcher');
      assert(MapView.highlightLabel() === 'Ratcatcher', 'Current-step map framing must still work');
      const originalHighlight = MapView.setHighlight;
      let highlighted = [];
      MapView.setHighlight = (name, markers) => { highlighted = markers; return originalHighlight(name, markers); };
      onQuestLog([{ id: 'Quest_FTUE_RC', s: 1, o: 'Objective1' }]);
      assert(highlighted.length === 1 && highlighted[0] === rat, 'Highlighted results must follow a change to the current objective');
      chooseSteps('all');
      assert(highlighted.length === 3, 'All steps must expand an existing highlighted quest');
      chooseSteps('current');
      assert(highlighted.length === 1, 'Current-only must narrow existing highlighted results');
      onQuestLog([{ id: 'Quest_FTUE_RC', s: 1, o: 'Objective2' }]);
      assert(highlighted.length === 2 && highlighted.includes(windmill), 'New current-step locations must not be trapped behind an older highlight');
      MapView.setHighlight = originalHighlight;
      showItem('Ratcatcher'); MapView.focusMarker(windmill); await wait(200);
      return 'PASS: all/selected/active, multiple selections, search, live completion, empty selection, hidden-marker picking, select-all/clear and explicit map navigation';
    })()`));
    fs.writeFileSync(path.join(workspace, 'test-fixtures/quest-map-filter.png'), (await win.webContents.capturePage()).toPNG());
    win.reload(); await new Promise(r => setTimeout(r, 1000));
    console.log(await win.webContents.executeJavaScript(`(() => {
      if (questMapMode !== 'selected' || questMapStepMode !== 'current' || !selectedMapQuests.has('Ratcatcher') || !selectedMapQuests.has("Cook's Assistant")) throw Error('Quest filter did not restore');
      return 'PASS: selected quests and current-step mode restored after reload';
    })()`));
    clearTimeout(timeout); app.exit(0);
  } catch (error) { console.error(error); app.exit(1); }
});
