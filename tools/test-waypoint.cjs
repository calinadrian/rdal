const { app, BrowserWindow, ipcMain } = require('electron');
const fs = require('fs'), path = require('path'), assert = require('assert/strict');
const workspace = path.resolve(__dirname, '..');
const root = path.resolve(process.argv[2] || workspace);
app.setPath('userData', require('./test-profile.cjs').testProfile('waypoint'));
ipcMain.handle('db:get', () => JSON.parse(fs.readFileSync(path.join(root, 'data/db.json'))));
ipcMain.handle('settings:get', () => ({ mode: 'window' }));
ipcMain.handle('update:get', () => ({ status: 'idle' }));
ipcMain.handle('preferences:get', () => ({}));
ipcMain.on('preferences:commit', e => { e.returnValue = { ok: true }; });
const wait = ms => new Promise(r => setTimeout(r, ms));
app.whenReady().then(async () => {
  const timeout = setTimeout(() => app.exit(1), 40000);
  try {
    const win = new BrowserWindow({ width: 1280, height: 850, show: false,
      webPreferences: { preload: path.join(root, 'app/preload.js'), backgroundThrottling: false } });
    const errors = [];
    win.webContents.on('console-message', (_, level, message) => { if (level >= 3) errors.push(message); });
    await win.loadFile(path.join(root, 'app/ui/index.html')); await wait(1000);
    win.showInactive();
    const js = code => win.webContents.executeJavaScript(code);
    const scene = await js(`(async () => {
      const check = (ok, message) => { if (!ok) throw Error(message); };
      const wait = ms => new Promise(r => setTimeout(r, ms));
      state.module = 'map'; setMapMode(true); renderModules(); initMap();
      const target = db.map.markers.find(m => m.c === 'ore' && m.n === 'Gold' && !m.d);
      window.testTarget = target;
      const me = { ok: true, x: target.x - 15000, y: target.y, z: target.z, yaw: 0 };
      MapView.setPlayer(me); MapView.setHighlight('Gold', [target]); MapView.focusMarker(target);
      MapView.centerOnPlayer(0.6); await wait(350);
      check(!document.querySelector('#map-waypoint').hidden, 'Selection shows navigation');
      check(document.querySelector('#map-waypoint span').textContent.startsWith('150 m'), 'World units converted to metres');
      check(Waypoint.bearing(target, me).angle === 0, 'Facing destination points up');
      check(Waypoint.bearing(target, {...me, yaw: 90}).angle === -90, 'Turning right rotates bearing left');
      check(Waypoint.bearing({x: me.x, y: me.y + 5000}, me).angle === 90, 'Positive map Y points right when facing positive X');
      check(Math.abs(Waypoint.bearing(target, {...me, yaw: 359}).angle - 1) < .01, 'Yaw wrap uses shortest bearing');
      MapView.setPlayer({...me, x: target.x - 20000, yaw: 90}); await wait(80);
      check(document.querySelector('#map-waypoint span').textContent.startsWith('200 m'), 'Movement updates distance');
      check(document.querySelector('#map-waypoint svg').style.transform === 'rotate(-90deg)', 'Live yaw updates visible arrow');
      MapView.setPlayer({...me, x: target.x - 500}); await wait(80);
      check(document.querySelector('#map-waypoint span').textContent.includes('Arrived'), 'Arrival threshold');
      check(document.querySelector('#map-waypoint svg').style.visibility === 'hidden', 'No spinning arrow on arrival');
      MapView.setPlayer({ok: false}); await wait(80);
      check(document.querySelector('#map-waypoint span').textContent.includes('Waiting'), 'Offline does not invent a bearing');
      MapView.setPlayer(me);
      const other = db.map.markers.find(m => m.d && Number.isFinite(m.x));
      MapView.setDestination(other); await wait(80);
      check(MapView.waypoint().blocked.startsWith('Enter '), 'Cross-dungeon destination explains transition');
      check(document.querySelector('#map-waypoint svg').style.visibility === 'hidden', 'No bearing through unrelated layers');
      MapView.setHighlight('Gold', [target]);
      MapView.setEnabled('ore', false);
      check(MapView.minimapScene(100).waypoint.x === target.x, 'Selected destination survives filters and minimap range');
      document.querySelector('#map-waypoint button').click(); await wait(80);
      check(!MapView.waypoint() && document.querySelector('#map-waypoint').hidden, 'Stop clears map and minimap destination');
      MapView.setHighlight(null); check(!MapView.waypoint(), 'Clear highlight clears destination');
      MapView.setEnabled('ore', true); MapView.focusMarker(target); await wait(400);
      const canvas = document.querySelector('#map'), rect = canvas.getBoundingClientRect(), p = MapView.screenOf(target);
      const event = {bubbles: true, clientX: rect.x + p.x, clientY: rect.y + p.y};
      canvas.dispatchEvent(new MouseEvent('mousemove', event));
      MapView.setDestination(null);
      canvas.dispatchEvent(new MouseEvent('mousedown', event)); canvas.dispatchEvent(new MouseEvent('mouseup', event));
      check(MapView.waypoint()?.x === target.x, 'Actual map marker click selects destination');
      MapView.setHighlight(null);
      const entrance = db.map.markers.find(m => m.enter && !m.d);
      MapView.setEnabled(entrance.c, true); MapView.focusMarker(entrance); await wait(350);
      const click = (point, type, extra = {}) => {
        const r = canvas.getBoundingClientRect();
        canvas.dispatchEvent(new MouseEvent(type, {bubbles: true, clientX: r.x + point.x, clientY: r.y + point.y, ...extra}));
      };
      const atEntrance = MapView.screenOf(entrance);
      MapView.setDestination(null);
      click(atEntrance, 'mousedown'); click(atEntrance, 'mouseup');
      check(MapView.layer() === null && MapView.waypoint()?.x === entrance.x, 'Left-click dungeon selects entrance without opening it');
      click(atEntrance, 'mousemove');
      check(document.querySelector('#map-tip').textContent.includes('Right-click'), 'Dungeon tooltip explains both actions');
      click(atEntrance, 'contextmenu', {button: 2}); await wait(450);
      check(MapView.layer()?.id === entrance.enter, 'Right-click dungeon opens floor plan');
      const dungeon = MapView.layer();
      MapView.setLayer(dungeon, 0); await wait(350);
      const floorPoint = {x: canvas.getBoundingClientRect().width / 2, y: canvas.getBoundingClientRect().height / 2};
      document.querySelector('#map-add-waypoint').click(); click(floorPoint, 'mousedown'); click(floorPoint, 'mouseup');
      check(MapView.waypoint()?.n.startsWith('My waypoint'), 'Custom dungeon waypoint is created');
      check(MapView.waypoint().blocked.startsWith('Enter '), 'Custom dungeon waypoint retains its dungeon');
      MapView.setPlayer({ok: true, x: MapView.waypoint().x, y: MapView.waypoint().y,
        z: (dungeon.bounds.minZ + dungeon.bounds.maxZ) / 2, yaw: 0});
      check(MapView.waypoint().blocked === null || MapView.waypoint().blocked.startsWith('Go to Level '), 'Dungeon pin retains its selected floor');
      MapView.setPlayer(me); MapView.setLayer(null); MapView.focusMarker(target); await wait(400);
      const point = MapView.screenOf(target);
      const before = {...MapView.waypoint()};
      click(point, 'mousedown', {button: 2}); click(point, 'mouseup', {button: 2});
      check(MapView.waypoint().x === before.x, 'Right mouse button does not trigger left selection');
      click(point, 'contextmenu', {button: 2});
      check(MapView.waypoint()?.n === 'My waypoint', 'Right-click map places own waypoint');
      check(Math.abs(MapView.waypoint().x - target.x) < 1 && Math.abs(MapView.waypoint().y - target.y) < 1, 'Screen position converts exactly to world coordinates');
      check(MapView.minimapScene(1).waypoint.n === 'My waypoint', 'Own waypoint reaches minimap beyond its range');
      document.querySelector('#map-add-waypoint').click();
      check(canvas.classList.contains('placing-waypoint'), 'Add waypoint starts placement mode');
      window.dispatchEvent(new KeyboardEvent('keydown', {key: 'Escape'}));
      check(!canvas.classList.contains('placing-waypoint'), 'Escape cancels placement');
      document.querySelector('#map-add-waypoint').click();
      click(point, 'mousedown'); click({x: point.x + 40, y: point.y}, 'mousemove'); click({x: point.x + 40, y: point.y}, 'mouseup');
      check(canvas.classList.contains('placing-waypoint'), 'Dragging pans without placing a waypoint');
      click(point, 'mousedown'); click(point, 'mouseup');
      check(!canvas.classList.contains('placing-waypoint') && MapView.waypoint().n === 'My waypoint', 'Placement button adds waypoint with left-click');
      const custom = MapView.screenOf(MapView.waypoint());
      click({x:custom.x, y:custom.y - 10}, 'mousedown'); click({x:custom.x, y:custom.y - 10}, 'mouseup');
      check(MapView.waypoint() === null, 'Clicking custom pin again removes it even over another marker');
      document.querySelector('#map-add-waypoint').click(); click(point, 'mousedown'); click(point, 'mouseup');
      document.querySelector('#map-waypoint button').click();
      check(MapView.waypoint() === null, 'Stop removes own waypoint');
      MapView.setHighlight('Gold', [target]); MapView.centerOnPlayer(0.6); await wait(400);
      return MapView.minimapScene(27000);
    })()`);
    fs.writeFileSync(path.join(workspace, 'test-fixtures/waypoint-map.png'), (await win.webContents.capturePage()).toPNG());
    // Use the real preload event for opening/closing the game's map; opening clears search highlights.
    win.webContents.send('game-map', true); await wait(200);
    const placed = await js(`(() => {
      const canvas = document.querySelector('#map'), r = canvas.getBoundingClientRect(), p = MapView.screenOf(testTarget);
      document.querySelector('#map-add-waypoint').click();
      const e = {bubbles: true, clientX: r.x + p.x, clientY: r.y + p.y};
      canvas.dispatchEvent(new MouseEvent('mousedown', e)); canvas.dispatchEvent(new MouseEvent('mouseup', e));
      if (MapView.waypoint()?.n !== 'My waypoint') throw Error('Place custom waypoint while map is open');
      return MapView.waypoint();
    })()`);
    for (let cycle = 0; cycle < 3; cycle++) {
      win.webContents.send('game-map', false); await wait(100);
      assert.deepEqual(await js(`MapView.waypoint()`), placed, 'Closing map keeps custom waypoint');
      win.webContents.send('game-map', true); await wait(100);
      assert.deepEqual(await js(`MapView.waypoint()`), placed, 'Reopening map keeps custom waypoint');
      assert.equal(await js(`document.querySelector('#map-waypoint').hidden`), false);
      assert.deepEqual(await js(`MapView.minimapScene(1).waypoint`), placed, 'Minimap keeps destination across map toggles');
    }
    await js(`document.querySelector('#map-waypoint button').click()`);
    win.webContents.send('game-map', false); await wait(100);
    win.webContents.send('game-map', true); await wait(100);
    assert.equal(await js(`MapView.waypoint()`), null, 'Removed waypoint does not come back on reopen');
    win.webContents.send('game-map', false); await wait(100);
    await js(`MapView.setDestination({...testTarget, custom: true, n: 'My waypoint'});`); await wait(100);
    fs.writeFileSync(path.join(workspace, 'test-fixtures/waypoint-custom.png'), (await win.webContents.capturePage()).toPNG());
    const mm = new BrowserWindow({ width: 264, height: 390, show: false, transparent: true, frame: false,
      webPreferences: { preload: path.join(root, 'app/minimap-preload.js'), backgroundThrottling: false } });
    await mm.loadFile(path.join(root, 'app/ui/minimap.html'));
    mm.showInactive();
    mm.webContents.send('minimap:active', true);
    mm.webContents.send('minimap:options', {size: 200, rotate: true, zoom: 0});
    mm.webContents.send('minimap:scene', scene); await wait(700);
    const run = code => mm.webContents.executeJavaScript(code);
    assert.equal(await run(`document.querySelector('#minimap-waypoint').hidden`), false);
    assert.match(await run(`document.querySelector('#minimap-waypoint span').textContent`), /150 m/);
    mm.webContents.send('minimap:player', {...scene.player, yaw: 90}); await wait(800);
    assert(Math.abs(await run(`parseFloat(document.querySelector('#minimap-waypoint svg').style.transform.slice(7))`) + 90) < .25,
      'Live heading glides to the correct bearing');
    assert.equal(await run(`document.body.scrollWidth <= innerWidth`), true, 'Overlay fits narrow window');
    fs.writeFileSync(path.join(workspace, 'test-fixtures/waypoint-minimap.png'), (await mm.webContents.capturePage()).toPNG());
    mm.webContents.send('minimap:scene', {ok: false, waypoint: scene.waypoint}); await wait(100);
    assert.match(await run(`document.querySelector('#minimap-waypoint span').textContent`), /Waiting/);
    mm.webContents.send('minimap:scene', {...scene, waypoint: null}); await wait(100);
    assert.equal(await run(`document.querySelector('#minimap-waypoint').hidden`), true);
    assert.deepEqual(errors, [], 'No renderer errors');
    clearTimeout(timeout);
    console.log('PASS: custom waypoint placement, repeated map close/reopen retention, explicit removal, dungeon left-select/right-open, floor context, live navigation and minimap rotation/layout');
    app.exit(0);
  } catch (error) { console.error(error); app.exit(1); }
});
