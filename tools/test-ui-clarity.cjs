// Exercise user journeys in real Chromium with an isolated preference profile.
const { app, BrowserWindow, ipcMain } = require('electron');
const fs = require('fs');
const path = require('path');
const assert = require('assert/strict');
const root = path.resolve(__dirname, '..');
const target = path.resolve(process.argv.filter(a => !a.startsWith('--'))[2] || root);
app.setPath('userData', require('./test-profile.cjs').testProfile('ui-clarity'));
let preferences = {};
ipcMain.handle('db:get', () => JSON.parse(fs.readFileSync(path.join(target, 'data/db.json'))));
ipcMain.handle('settings:get', () => ({ mode: 'window', hotkey: 'Control+Shift+L' }));
ipcMain.handle('preferences:get', () => preferences);
ipcMain.handle('update:get', () => ({ status: 'idle', current: '0.1.1' }));
ipcMain.on('preferences:commit', (event, patch) => {
  Object.assign(preferences, patch); event.returnValue = { ok: true };
});
const timer = setTimeout(() => { console.error('UI clarity test timed out'); app.exit(1); }, 45000);
app.whenReady().then(async () => {
  const win = new BrowserWindow({ width: 1380, height: 860, show: false,
    webPreferences: { preload: path.join(target, 'app/preload.js'), sandbox: false, backgroundThrottling: false } });
  const js = async code => { try { return await win.webContents.executeJavaScript(code); } catch (error) { console.error('Renderer step:', code); throw error; } };
  win.webContents.on('console-message', (_event, level, message) => { if (level >= 2) console.error('Renderer:', message); });
  const tick = () => new Promise(r => setTimeout(r, 220));
  const capture = async name => {
    await tick();
    fs.writeFileSync(path.join(root, 'test-fixtures', `clarity-${name}.png`), (await win.webContents.capturePage()).toPNG());
  };
  try {
    await win.loadFile(path.join(target, 'app/ui/index.html')); win.showInactive(); await tick();
    assert(await js(`!history.length && $('#btn-back').disabled`));
    assert(await js(`getComputedStyle($('#detail')).display === 'none'`));
    await js(`selectModule('monsters'); state.filter='Wolf'; go({type:'source',arg:'Wolf'},{detail:null});
      $('#content').scrollTop=160; window.originScroll=$('#content').scrollTop;
      $('#search').value='Feathers'; $('#search').dispatchEvent(new Event('input'));`);
    await tick();
    assert(await js(`state.view.type==='search' && $('#search').getAttribute('aria-label')==='Search everything'`));
    await js(`[...document.querySelectorAll('#content .loot-row')].find(el => el.querySelector('.name')?.textContent==='Feathers').click()`);
    assert(await js(`state.detail==='Feathers' && getComputedStyle($('#detail')).display!=='none'`));
    assert(await js(`$('#detail').textContent.includes('Add to wishlist') && $('#detail .detail-close')`));
    await capture('desktop-item');
    await js(`window.source=ent('Feathers').droppedBy.find(s=>markersFor(s.from).length).from;
      open(source); $('#detail').scrollTop=110; window.sourceScroll=$('#detail').scrollTop;
      showOnMap(source);`);
    await tick();
    assert(await js(`state.module==='map' && !$('#map-layer').hidden && !$('#map-filters').hidden`));
    await js(`back()`);
    assert(await js(`state.module==='monsters' && state.view.type==='source' && state.view.arg===source && state.detail==='Feathers' && state.filter==='Wolf' && $('#search').value==='Feathers' && $('#detail').scrollTop===sourceScroll`));
    await js(`back(); back(); back()`);
    assert(await js(`state.module==='monsters' && state.view.arg==='Wolf' && state.filter==='Wolf' && $('#content').scrollTop===originScroll`));
    await js(`state.filter='zz-no-matching-creature'; renderList()`);
    assert(await js(`$('.filter-count').textContent==='0 entries found' && $('#list').textContent.includes('Try a shorter name')`));
    await js(`$('.filter-clear').click()`);
    assert(await js(`state.filter==='' && document.activeElement.id==='section-filter'`));
    await js(`state.filter='Wolf'; renderList(); document.querySelector('#list .list-item').focus()`);
    win.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Enter' });
    win.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Enter' }); await tick();
    assert(await js(`state.view.type==='source' && state.view.arg.includes('Wolf')`));
    await js(`showItem('Feathers'); $('#detail .detail-close').click()`);
    assert(await js(`state.detail===null && getComputedStyle($('#detail')).display==='none'`));
    await js(`$('#search').value='xxnoresults'; $('#search').dispatchEvent(new Event('input'));`); await tick();
    assert(await js(`$('#content').textContent.includes('No matches. Try a shorter')`));
    await js(`$('#search').value='x'; $('#search').dispatchEvent(new Event('input'));`); await tick();
    assert(await js(`$('#content').textContent.includes('Type at least two characters')`));
    await js(`$('#search-clear').click()`);
    assert(await js(`state.view.type==='source' && !$('#search').value`));
    await js(`$('#search').value='Ratcatcher'; $('#search').dispatchEvent(new Event('input')); selectModule('map')`); await tick();
    assert(await js(`state.module==='map' && state.view===null`));
    await js(`wish.add('Feathers'); wish.add('Wolf'); saveWish(); selectModule('wishlist');
      $('#section-filter').value='Feathers'; $('#section-filter').dispatchEvent(new Event('input'));`);
    assert(await js(`$('#content .loot-row .name').textContent==='Feathers' && $('#content .loot-row .name').textContent!=='Wolf' && $('#content').querySelectorAll('.loot-row').length===1`));
    console.log('PASS: scoped search, empty recovery, detail closing and search → item → source → map → Back context');

    await js(`selectModule('crafting');
      window.recipeItem=Object.values(E).find(e=>e.kind==='item' && e.journal && e.recipes.some(r=>r.materials?.length && !r.facility?.startsWith('Vendor: ')));
      go({type:'journal',arg:recipeItem.name},{detail:null}); state.filter='bar'; renderList();
      $('#content').scrollTop=200; window.recipeScroll=$('#content').scrollTop;
      showItem(recipeItem.recipes.find(r=>r.materials?.length).materials[0].item); back();`);
    assert(await js(`state.view.arg===recipeItem.name && state.filter==='bar' && $('#content').scrollTop===recipeScroll`));
    assert(await js(`$('#content').textContent.includes('Learning status unknown') && $('#content .journal-description')`));
    await js(`RecipeKnowledge.ingest({character:'A'.repeat(32),session:'test',recipes:[]}); render();`);
    assert(await js(`$('#content .progress-context').textContent.includes('Saved progress · last updated')`));
    await js(`$('#content').scrollTop=0`);
    await capture('desktop-recipe');
    await js(`selectModule('quests'); questLog=null; render(); showItem('Ratcatcher')`);
    assert(await js(`$('#detail').textContent.includes('Progress unknown') && !$('#detail [role=progressbar]')`));
    assert(await js(`$('#content .progress-context').textContent.includes('Progress unknown') && !$('#content .quest-journal-progress')`));
    await js(`onQuestLog([{id:'Quest_FTUE_RC',s:1,o:'Objective2'}]); renderDetail();`);
    assert(await js(`$('#detail .current-objective') && $('#detail .progress-context').textContent.includes('Saved progress · last updated')`));
    console.log('PASS: recipe → ingredient → Back preserves context; saved and unknown progress; current quest objective');

    await js(`selectModule('map'); MapView.setHighlight(null); syncMapHighlight(); for(const id of [...db.map.categories.map(c=>c.id),'npc']) MapView.setEnabled(id,false);`);
    await tick();
    assert(await js(`!$('#map-empty').hidden && $('#map-empty').textContent.includes('filters')`));
    await js(`$('#map-filters').click()`);
    assert(await js(`!$('#map-legend').hidden && $('#map-filters').getAttribute('aria-expanded')==='true' && $('#map-filters').textContent.includes('(')`));
    await js(`$('#map-legend .map-filter-header button').click()`);
    assert(await js(`MapView.isEnabled('chest') && questMapMode==='all' && liveCreaturePool===null && $('#map-filters').textContent==='Filters'`));
    await js(`MapView.setLayer(null); for(const id of [...db.map.categories.map(c=>c.id),'npc']) MapView.setEnabled(id,id==='ore'); MapView.fit(false); MapView.zoom(.05);`);
    await tick();
    assert(await js(`!$('#map-empty').hidden && $('#map-empty').textContent.includes('Zoom in')`));
    await js(`for(const id of [...db.map.categories.map(c=>c.id),'npc']) MapView.setEnabled(id,id==='npc');`);
    await tick();
    assert(await js(`$('#map-empty').textContent.includes('load your character')`));
    await js(`resetMapFilters(); $('#map-filters').click()`);
    await capture('desktop-map');
    await js(`$('#map-filters').click()`); await capture('desktop-map-filters'); await js(`$('#map-filters').click()`);
    win.setSize(900, 680); await tick();
    await js(`selectModule('monsters'); go({type:'source',arg:'Wolf'},{detail:null}); showItem('Feathers')`);
    assert(await js(`getComputedStyle($('#detail .detail-navigation')).display!=='none' && $('#detail .detail-navigation .content-back')`));
    await capture('compact-item');
    await js(`$('#detail .detail-close').click(); selectModule('map');
      MapView.setLayer(db.map.dungeons.find(d=>d.levels?.length>1));`);
    await tick();
    assert(await js(`!$('#map-level-label').hidden && !$('#map-level').hidden`));
    await capture('compact-dungeon');
    const overflow = await js(`['.titlebar','.map-tools','#detail'].filter(s=>{const e=$(s);return e.clientWidth && e.scrollWidth>e.clientWidth+1})`);
    assert.deepEqual(overflow, []);
    console.log('PASS: map reset/count, filter/zoom/offline recovery, labeled dungeon floors, compact navigation and no control overflow');
    clearTimeout(timer); app.exit(0);
  } catch (error) { console.error(error); clearTimeout(timer); app.exit(1); }
});
